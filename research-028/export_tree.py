"""Export a searched strategy tree as a Rocq file checked by `linear_treeb`.

Python only proposes the tree: for each node, Black's reply to each White move;
for each leaf, one information set I0. Inside Rocq, `build_decoder` (plain
Gaussian elimination, no correctness proof needed) computes decoders for I0 and
for its complement among the free cells. `linear_leafb` then re-checks them,
and its soundness theorem does the rest. A wrong tree cannot pass: the
`vm_compute` check would return false.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from fragment_search import games
from tree_extend import code_leaf

HERE = Path(__file__).resolve().parent

PRELUDE = r'''(** Generated by research-028/export_tree.py. Python proposes the tree; Rocq checks it.
    The position is reached by the listed game prefix; it is not forced from the empty board. *)
From Stdlib Require Import List Arith Bool Lia NArith.
From QubicTrusted Require Import Rules.
From QubicAgent Require Import Minimax RulesFacts SafePairing TreeCertificates
  ZLinearAlgebra ZLinearDefense ZZLinearTrees.
Import ListNotations.

Definition scheduled_white (cells : list cell) : WhiteStrategy :=
  fun st => nth (length (white_stones st)) cells 0.
Definition scheduled_black (cells : list cell) : BlackStrategy :=
  fun st => nth (length (black_stones st)) cells 0.

Lemma prefix_validity : forall n turn st w b,
  n + length (history st) <= 125 -> valid_state st ->
  valid_state (final_state (step_game n turn st w b)).
Proof.
  induction n as [|n IH]; intros turn st w b Hlen Hvalid; [exact Hvalid|].
  rewrite step_game_equation. cbn zeta.
  set (next := move_state turn st (if turn then w st else b st)).
  assert (Hnext : valid_state next) by (apply move_preserves_validity; [exact Hvalid|lia]).
  destruct (move_result turn next); [exact Hnext|].
  apply IH; [unfold next; rewrite move_state_history; lia|exact Hnext].
Qed.

(** Unverified decoder construction: Gaussian elimination with pivots in [pivots].
    Soundness never depends on it, because [linear_leafb] re-checks the result. *)
Fixpoint reduce_by (basis : Decoder) (w : N) : N :=
  match basis with
  | [] => w
  | (p, b) :: rest => reduce_by rest (if bit w p then N.lxor w b else w)
  end.

Fixpoint first_pivot (pivots : list cell) (w : N) : option cell :=
  match pivots with
  | [] => None
  | c :: rest => if bit w c then Some c else first_pivot rest w
  end.

Definition add_row (pivots : list cell) (basis : Decoder) (w : N) : Decoder :=
  let w' := reduce_by basis w in
  match first_pivot pivots w' with
  | None => basis
  | Some p => (p, w') :: map (fun pb => (fst pb,
      if bit (snd pb) p then N.lxor (snd pb) w' else snd pb)) basis
  end.

Definition build_decoder (pivots : list cell) (rows : list N) : Decoder :=
  fold_left (add_row pivots) rows [].

Definition free_cells (st : GameState) : list cell :=
  filter (fun c => negb (occupied st c)) (seq 0 125).

(** A leaf stores its information set I0 as a 125-bit mask; I1 is the rest of the free cells. *)
Definition leaf_for (st : GameState) (mask : N) : LinearDefenseCertificate :=
  let rows := residual_rows st in
  let i0 := filter (fun c => bit mask c) (free_cells st) in
  let i1 := filter (fun c => negb (bit mask c)) (free_cells st) in
  LinearLeaf (build_decoder i0 rows) (build_decoder i1 rows).

Inductive Plan : Type :=
| PLeaf : N -> Plan
| PNode : list (cell * (cell * Plan)) -> Plan.

Definition after (st : GameState) (x r : cell) : GameState :=
  move_state false (move_state true st x) r.

Fixpoint lookup {A} (default : A) (x : cell) (t : list (cell * A)) : A :=
  match t with
  | [] => default
  | (y, a) :: rest => if Nat.eqb x y then a else lookup default x rest
  end.

Fixpoint to_cert (plan : Plan) (st : GameState) {struct plan} : LinearDefenseCertificate :=
  match plan with
  | PLeaf i0 => leaf_for st i0
  | PNode kids =>
      let fix go (ks : list (cell * (cell * Plan))) :=
        match ks with
        | [] => []
        | (x, (r, sub)) :: rest => (x, (r, to_cert sub (after st x r))) :: go rest
        end in
      let table := go kids in
      LinearDefenseNode (fun x => fst (lookup (0, LinearLeaf [] []) x table))
        (* default leaf never passes linear_leafb on a live position *)
        (fun x => snd (lookup (0, LinearLeaf [] []) x table))
  end.
'''


def rl(xs) -> str:
    return '[' + ';'.join(str(x) for x in xs) + ']'


LEAF_SETS: dict = {}


def collect_leaves(white, black, tree, acc) -> None:
    if tree == 'win':
        return
    if tree == 'leaf':
        acc.append((tuple(white), tuple(black)))
        return
    for k, (r, sub) in tree.items():
        collect_leaves(white + [int(k)], black + [r], sub, acc)


def _leaf_job(wb):
    return wb, code_leaf(list(wb[0]), list(wb[1]))


def precompute_leaves(white, black, tree, workers=20) -> None:
    """Information sets for every leaf, in parallel (fills LEAF_SETS)."""
    import multiprocessing as mp
    import time
    acc: list = []
    collect_leaves(white, black, tree, acc)
    todo = [wb for wb in dict.fromkeys(acc) if wb not in LEAF_SETS]
    t0 = time.time()
    print(f'  computing information sets for {len(todo)} leaves on {workers} workers', flush=True)
    with mp.Pool(workers) as pool:
        for i, (wb, sets) in enumerate(pool.imap_unordered(_leaf_job, todo, chunksize=64)):
            if sets is None:
                raise RuntimeError(f'leaf fails in Python: {wb}')
            LEAF_SETS[wb] = sets
            if (i + 1) % 5000 == 0:
                print(f'    {i + 1}/{len(todo)} leaves, {time.time() - t0:.0f}s', flush=True)


def plan_text(white, black, tree, depth_indent=1) -> str:
    if tree == 'win':
        # Black's reply completes a line; roundb accepts before consulting the child.
        return 'PLeaf 0%N'
    if tree == 'leaf':
        key = (tuple(white), tuple(black))
        sets = LEAF_SETS[key] if key in LEAF_SETS else code_leaf(white, black)
        if sets is None:
            raise RuntimeError(f'leaf fails in Python: W{white} B{black}')
        return f'PLeaf {sum(1 << c for c in sets[0])}%N'
    pad = '  ' * depth_indent
    items = []
    for m, (r, sub) in sorted(((int(k), v) for k, v in tree.items())):
        items.append(f'({m}, ({r}, ' + plan_text(white + [m], black + [r], sub, depth_indent + 1) + '))')
    return 'PNode [\n' + pad + (';\n' + pad).join(items) + ']'


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('tree_json')
    ap.add_argument('--game', required=True)
    ap.add_argument('--round', type=int, required=True)
    ap.add_argument('--name', required=True, help='Rocq module name')
    args = ap.parse_args()
    data = json.loads(Path(args.tree_json).read_text(encoding='utf-8'))
    # depth-1 probe format -> generic format
    tree = {k: ([v['reply'], 'leaf'] if isinstance(v, dict) else v) for k, v in data.items()}
    if any(v is None or v[0] is None for v in tree.values()):
        raise SystemExit('tree has uncovered White moves; nothing to export')
    white, black = games()[args.game]
    white, black = white[:args.round], black[:args.round]
    hist = [c for pair in zip(white, black) for c in pair]
    plies = len(hist)
    body = PRELUDE + f'''
Definition white_history : list cell := {rl(white)}.
Definition black_history : list cell := {rl(black)}.
Definition start_state : GameState := make_state
  {rl(reversed(white))} {rl(reversed(black))}
  {rl(reversed(hist))}.

Theorem start_state_is_legal_prefix :
  final_state (step_game {plies} true initial_state
    (scheduled_white white_history) (scheduled_black black_history)) = start_state.
Proof. vm_compute. reflexivity. Qed.

Theorem start_state_valid : valid_state start_state.
Proof.
  rewrite <- start_state_is_legal_prefix. apply prefix_validity;
    [cbn; lia|apply initial_state_valid].
Qed.

Definition plan : Plan := {plan_text(white, black, tree)}.

Definition certificate : LinearDefenseCertificate := to_cert plan start_state.

Theorem certificate_checks : linear_treeb certificate start_state = true.
Proof. vm_compute. reflexivity. Qed.

(** After this {plies}-ply prefix, Black has a strategy that never loses. *)
Theorem start_state_total_defense : exists b : BlackStrategy, forall w : WhiteStrategy,
  outcome (step_game {125 - plies} true start_state w b) <> WhiteWins.
Proof.
  exact (checked_linear_tree_total_defense certificate start_state {125 - plies}
    certificate_checks start_state_valid eq_refl).
Qed.

Print Assumptions start_state_total_defense.
'''
    out = HERE / f'{args.name}.v'
    out.write_text(body, encoding='utf-8')
    print(f'wrote {out.name}: {plies}-ply prefix, {len(body) // 1024} KiB', flush=True)


if __name__ == '__main__':
    main()
