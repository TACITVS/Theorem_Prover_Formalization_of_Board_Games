(** * MNKExactSpeed.v: Exact Winning Speeds

    A winning strategy is optimal in speed when it wins within d moves and
    no strategy wins within d - 1.  Here d counts the winner's own moves; in
    the strong game, d moves of Player 1 take 2d - 1 plies.  The upper bounds
    are the checked winning strategies of MNKPhaseTransition.v and
    MNKMakerWins.v.  The lower bounds come from [mnk_no_win_before_k] (no
    k in a row in fewer than k moves) or from Breaker certificates
    (MNKBreakerCerts.v, generated by solver/breaker_cert.c, checked by
    [check_br]).

    Main results:
      - [mnk_m_n_3_exactly_3_moves]: on every board with m, n >= 4, Player 1
        forces 3 in a row in exactly 3 own moves (5 plies).
      - [mnk_3_n_3_exactly_4_moves]: on 3 x n, for 4 <= n <= 21, in exactly
        4 own moves (7 plies).
      - The same speeds hold in the Maker-Breaker game
        ([mnk_m_n_3_mb_exactly_3_moves], [mnk_3_n_3_mb_exactly_4_moves]).
      - [mnk_3_3_3_mb_exactly_4_moves]: Maker wins Maker-Breaker tic-tac-toe
        in exactly 4 moves.
      - [mnk_5_5_4_mb_exactly_5_moves]: Maker wins Maker-Breaker (5, 5, 4)
        in exactly 5 moves.

    Zero axioms, zero admits. *)

From Stdlib Require Import List Arith Lia Bool.
Import ListNotations.
From MNK Require Import MNKBoard MNKGame MNKPhaseTransition MNKErdosSelfridge.
From MNK Require Import MNKBreakerCert MNKBreakerCerts MNKMakerWins.

(* ========================================================================= *)
(** * 1. Three in a row on boards with m, n >= 4                            *)
(* ========================================================================= *)

Theorem mnk_m_n_3_exactly_3_moves : forall m n, 4 <= m -> 4 <= n ->
  forces_win (gen_lines m n 3) P1 3 (empty_board (m * n)) /\
  ~ forces_win (gen_lines m n 3) P1 2 (empty_board (m * n)).
Proof.
  intros m n Hm Hn. split.
  - exact (mnk_m_n_3_first_player_win_5_plies m n Hm Hn).
  - apply mnk_no_forced_win_before_k. lia.
Qed.

Theorem mnk_m_n_3_mb_exactly_3_moves : forall m n, 4 <= m -> 4 <= n ->
  maker_wins (gen_lines m n 3) P1 3 (empty_board (m * n)) /\
  ~ maker_wins (gen_lines m n 3) P1 2 (empty_board (m * n)).
Proof.
  intros m n Hm Hn. split.
  - apply forces_win_maker_wins. exact (mnk_m_n_3_first_player_win_5_plies m n Hm Hn).
  - apply mnk_no_win_before_k. lia.
Qed.

(* ========================================================================= *)
(** * 2. Three in a row on 3 x n                                            *)
(* ========================================================================= *)

Definition br_cert_3_n_3 (n : nat) : brcert :=
  match n with
  | 4 => br_cert_3_4_3_within_3
  | 5 => br_cert_3_5_3_within_3
  | 6 => br_cert_3_6_3_within_3
  | 7 => br_cert_3_7_3_within_3
  | 8 => br_cert_3_8_3_within_3
  | 9 => br_cert_3_9_3_within_3
  | 10 => br_cert_3_10_3_within_3
  | 11 => br_cert_3_11_3_within_3
  | 12 => br_cert_3_12_3_within_3
  | 13 => br_cert_3_13_3_within_3
  | 14 => br_cert_3_14_3_within_3
  | 15 => br_cert_3_15_3_within_3
  | 16 => br_cert_3_16_3_within_3
  | 17 => br_cert_3_17_3_within_3
  | 18 => br_cert_3_18_3_within_3
  | 19 => br_cert_3_19_3_within_3
  | 20 => br_cert_3_20_3_within_3
  | 21 => br_cert_3_21_3_within_3
  | _ => BrShort
  end.

Lemma br_cert_3_n_3_checked :
  forallb (fun n => check_br (gen_lines 3 n 3) P1 (Some 3) (empty_board (3 * n))
                             (br_cert_3_n_3 n))
          (seq 4 18) = true.
Proof. vm_compute. reflexivity. Qed.

Theorem mnk_3_n_3_mb_no_win_within_3 : forall n, 4 <= n <= 21 ->
  ~ maker_wins (gen_lines 3 n 3) P1 3 (empty_board (3 * n)).
Proof.
  intros n Hn.
  apply (check_br_within (gen_lines 3 n 3) P1 (gen_lines_nodup 3 n 3) (br_cert_3_n_3 n)).
  pose proof br_cert_3_n_3_checked as H. rewrite forallb_forall in H.
  apply H. apply in_seq. lia.
Qed.

Theorem mnk_3_n_3_exactly_4_moves : forall n, 4 <= n <= 21 ->
  forces_win (gen_lines 3 n 3) P1 4 (empty_board (3 * n)) /\
  ~ forces_win (gen_lines 3 n 3) P1 3 (empty_board (3 * n)).
Proof.
  intros n Hn. split.
  - apply mnk_3_n_3_first_player_win. lia.
  - intros Hw. apply (mnk_3_n_3_mb_no_win_within_3 n Hn).
    apply forces_win_maker_wins. exact Hw.
Qed.

Theorem mnk_3_n_3_mb_exactly_4_moves : forall n, 4 <= n <= 21 ->
  maker_wins (gen_lines 3 n 3) P1 4 (empty_board (3 * n)) /\
  ~ maker_wins (gen_lines 3 n 3) P1 3 (empty_board (3 * n)).
Proof.
  intros n Hn. split.
  - apply forces_win_maker_wins. apply mnk_3_n_3_first_player_win. lia.
  - exact (mnk_3_n_3_mb_no_win_within_3 n Hn).
Qed.

(* ========================================================================= *)
(** * 3. Maker-Breaker tic-tac-toe and (5, 5, 4)                             *)
(* ========================================================================= *)

Theorem mnk_3_3_3_mb_exactly_4_moves :
  maker_wins (gen_lines 3 3 3) P1 4 (empty_board (3 * 3)) /\
  ~ maker_wins (gen_lines 3 3 3) P1 3 (empty_board (3 * 3)).
Proof.
  split.
  - exact mnk_3_3_3_maker_wins.
  - apply (check_br_within _ _ (gen_lines_nodup 3 3 3) br_cert_3_3_3_within_3).
    vm_compute. reflexivity.
Qed.

Theorem mnk_5_5_4_mb_exactly_5_moves :
  maker_wins (gen_lines 5 5 4) P1 5 (empty_board (5 * 5)) /\
  ~ maker_wins (gen_lines 5 5 4) P1 4 (empty_board (5 * 5)).
Proof.
  split.
  - exact mnk_5_5_4_maker_wins.
  - apply (check_br_within _ _ (gen_lines_nodup 5 5 4) br_cert_5_5_4_within_4).
    vm_compute. reflexivity.
Qed.
