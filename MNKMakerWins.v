(** * MNKMakerWins.v: Maker-Breaker Wins, and Where They Differ from the Strong Game

    The certificates of MNKMakerWinCerts.v (generated by solver/mb_win_cert.c)
    are checked here with the sound checker [check_mb] (MNKMakerBreakerCert.v),
    and spread to whole families of boards with the embedding theorems of
    MNKMakerBreaker.v.

    Main results:
      - [mnk_3_3_3_maker_wins], [mnk_5_5_4_maker_wins]: Maker, moving first,
        wins the Maker-Breaker game on 3 x 3 with 3 in a row and on 5 x 5 with
        4 in a row.
      - [mnk_tic_tac_toe_gap]: tic-tac-toe is a draw, yet Maker wins its
        Maker-Breaker version.  The draw needs Player 2's own threats: no
        Breaker strategy alone can hold it.
      - [mnk_5_5_4_no_breaker_win]: likewise no Breaker strategy holds
        (5, 5, 4), so its draw (known, not formalized here) cannot come from
        [breaker_win_draw].
      - [mnk_maker_wins_k3_family], [mnk_maker_wins_k4_family]: Maker wins the
        Maker-Breaker game on every board with m, n >= 3 and k <= 3, and on
        every board with m, n >= 5 and k <= 4.

    Zero axioms, zero admits. *)

From Stdlib Require Import List Arith Lia.
From MNK Require Import MNKBoard MNKGame MNKPhaseTransition MNKErdosSelfridge.
From MNK Require Import MNKMakerBreaker MNKMakerBreakerCert MNKMakerWinCerts.

(* ========================================================================= *)
(** * 1. The checked certificates                                            *)
(* ========================================================================= *)

Theorem mnk_3_3_3_maker_wins :
  maker_wins (gen_lines 3 3 3) P1 mb_depth_3_3_3 (empty_board (3 * 3)).
Proof. apply (check_mb_sound _ _ mb_cert_3_3_3). vm_compute. reflexivity. Qed.

Theorem mnk_5_5_4_maker_wins :
  maker_wins (gen_lines 5 5 4) P1 mb_depth_5_5_4 (empty_board (5 * 5)).
Proof. apply (check_mb_sound _ _ mb_cert_5_5_4). vm_compute. reflexivity. Qed.

(* ========================================================================= *)
(** * 2. Maker-Breaker and the strong game differ                           *)
(* ========================================================================= *)

(** Tic-tac-toe is a draw, but Maker wins its Maker-Breaker version. *)
Theorem mnk_tic_tac_toe_gap :
  game_is_draw (gen_lines 3 3 3) (empty_board 9) /\
  exists d, maker_wins (gen_lines 3 3 3) P1 d (empty_board 9).
Proof.
  split.
  - exact mnk_3_3_3_draw.
  - exists mb_depth_3_3_3. exact mnk_3_3_3_maker_wins.
Qed.

(** No Breaker strategy holds (5, 5, 4). *)
Corollary mnk_5_5_4_no_breaker_win :
  ~ (forall d, ~ maker_wins (gen_lines 5 5 4) P1 d (empty_board (5 * 5))).
Proof. intros H. exact (H mb_depth_5_5_4 mnk_5_5_4_maker_wins). Qed.

(* ========================================================================= *)
(** * 3. Families of boards                                                  *)
(* ========================================================================= *)

(** A Maker win on m' x n' with k' in a row is a Maker win on every board
    containing m' x n' (either way round) with lines of length k <= k'. *)
Lemma maker_win_spreads : forall m' n' k' d m n k,
  maker_wins (gen_lines m' n' k') P1 d (empty_board (m' * n')) ->
  ((m' <= m /\ n' <= n) \/ (m' <= n /\ n' <= m)) -> k <= k' ->
  maker_wins (gen_lines m n k) P1 d (empty_board (m * n)).
Proof.
  intros m' n' k' d m n k Hw Hfit Hk.
  apply (mnk_maker_wins_shorter_lines m n k k'); [exact Hk |].
  destruct Hfit as [[Hm Hn] | [Hm Hn]].
  - exact (mnk_maker_wins_subboard m' n' m n k' P1 d Hm Hn Hw).
  - apply (mnk_maker_wins_subboard n' m' m n k' P1 d); [lia | lia |].
    apply mnk_maker_wins_transpose. exact Hw.
Qed.

Theorem mnk_maker_wins_k3_family : forall m n k, 3 <= m -> 3 <= n -> k <= 3 ->
  maker_wins (gen_lines m n k) P1 mb_depth_3_3_3 (empty_board (m * n)).
Proof.
  intros m n k Hm Hn Hk.
  apply (maker_win_spreads 3 3 3); [exact mnk_3_3_3_maker_wins | lia | exact Hk].
Qed.

Theorem mnk_maker_wins_k4_family : forall m n k, 5 <= m -> 5 <= n -> k <= 4 ->
  maker_wins (gen_lines m n k) P1 mb_depth_5_5_4 (empty_board (m * n)).
Proof.
  intros m n k Hm Hn Hk.
  apply (maker_win_spreads 5 5 4); [exact mnk_5_5_4_maker_wins | lia | exact Hk].
Qed.
