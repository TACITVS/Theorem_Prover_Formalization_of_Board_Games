"""Untrusted deterministic pairing search and Rocq witness emission.

Rocq independently checks the emitted data. This program searches only near
known cooperative histories; it makes no empty-board game-value claim.
"""
from __future__ import annotations

import argparse
import itertools
from pathlib import Path


def generate_lines() -> list[tuple[int, ...]]:
    def coordinate(mode: int, t: int) -> int:
        return mode if mode < 5 else t if mode == 5 else 4 - t
    lines = []
    for modes in itertools.product(range(7), repeat=3):
        if max(modes) < 5:
            continue
        line = tuple(sum(scale * coordinate(mode, t) for scale, mode in zip((1, 5, 25), modes))
                     for t in range(5))
        if line[0] < line[-1]:
            lines.append(line)
    assert len(lines) == len(set(lines)) == 109
    return sorted(lines)


LINES = generate_lines()


def wins(stones: set[int]) -> bool:
    return any(set(line) <= stones for line in LINES)


def matching(white: set[int], black: set[int]) -> list[int] | None:
    surviving = [line for line in LINES if not black.intersection(line)]
    if 2 * len(surviving) > 125 - len(white | black):
        return None
    adjacency = [[c for c in line if c not in white | black]
                 for line in surviving for _ in range(2)]
    right: dict[int, int] = {}

    def augment(slot: int, seen: set[int]) -> bool:
        for c in adjacency[slot]:
            if c in seen:
                continue
            seen.add(c)
            if c not in right or augment(right[c], seen):
                right[c] = slot
                return True
        return False

    for slot in range(len(adjacency)):
        if not augment(slot, set()):
            return None
    pairs: dict[int, list[int]] = {}
    for c, slot in right.items():
        pairs.setdefault(slot // 2, []).append(c)
    table = list(range(125))
    for pair in pairs.values():
        a, b = pair
        table[a], table[b] = b, a
    return table


WHITE10 = [121, 122, 103, 123, 109, 114, 94, 119, 49, 74]
BLACK10 = [0, 100, 95, 31, 81, 62, 108, 43, 29, 124]
WHITE_BASE = [10, 23, 25, 33, 35, 36, 37, 38, 41, 42, 43, 62, 90, 99, 102, 103]
BLACK_BASE = [0, 91, 83, 29, 81, 48, 31, 39, 40, 86, 60, 88, 12, 113, 22, 100]


def rocq_list(values) -> str:
    return '[' + ';'.join(map(str, values)) + ']'


def position_definitions(label: str, white: list[int], black: list[int]) -> str:
    assert len(white) == len(black)
    assert len(set(white + black)) == len(white + black)
    assert not wins(set(white)) and not wins(set(black))
    plies = 2 * len(white)
    history = list(itertools.chain.from_iterable(zip(white, black)))
    return f'''
Definition white{label} : list cell := {rocq_list(white)}.
Definition black{label} : list cell := {rocq_list(black)}.
Definition state{label} : GameState :=
  make_state {rocq_list(reversed(white))} {rocq_list(reversed(black))}
    {rocq_list(reversed(history))}.

Theorem state{label}_is_legal_prefix :
  final_state (step_game {plies} true initial_state
    (scheduled_white white{label}) (scheduled_black black{label})) = state{label}.
Proof. vm_compute. reflexivity. Qed.

Theorem state{label}_valid : valid_state state{label}.
Proof.
  rewrite <- state{label}_is_legal_prefix. apply prefix_preserves_validity;
    [cbn; lia|apply initial_state_valid].
Qed.

Theorem state{label}_nonterminal :
  length (history state{label}) = {plies} /\\ quiet state{label}.
Proof. vm_compute. repeat split; reflexivity. Qed.
'''


def generate() -> str:
    table10 = matching(set(WHITE10), set(BLACK10))
    assert table10 is not None
    replies = [0] * 125
    tables: list[list[int]] = [[] for _ in range(125)]
    white15, black15 = set(WHITE_BASE[:15]), set(BLACK_BASE[:15])
    branches = 0
    for x in range(125):
        if x in white15 | black15:
            continue
        after_white = white15 | {x}
        assert not wins(after_white), f'Immediate White win on {x}'
        for y in range(125):
            if y in after_white | black15:
                continue
            table = matching(after_white, black15 | {y})
            if table is not None:
                replies[x], tables[x] = y, table
                branches += 1
                break
        else:
            raise RuntimeError(f'No one-round pairing defense for White {x}')
    assert branches == 95
    output = '''(** Generated by generate_witnesses.py; all data checked below in Rocq.
    These are local continuations, NOT a strategy from the empty board. *)
From Stdlib Require Import List Arith Bool Lia.
From QubicTrusted Require Import Rules.
From QubicAgent Require Import Minimax RulesFacts SafePairing TreeCertificates.
Import ListNotations.

Definition scheduled_white (cells : list cell) : WhiteStrategy :=
  fun st => nth (length (white_stones st)) cells 0.
Definition scheduled_black (cells : list cell) : BlackStrategy :=
  fun st => nth (length (black_stones st)) cells 0.

Lemma prefix_preserves_validity : forall n turn st w b,
  n + length (history st) <= 125 -> valid_state st ->
  valid_state (final_state (step_game n turn st w b)).
Proof.
  induction n as [|n IH]; intros turn st w b Hlen Hvalid; [exact Hvalid|].
  rewrite step_game_equation. cbn zeta.
  set (next := move_state turn st (if turn then w st else b st)).
  assert (Hnext : valid_state next) by (apply move_preserves_validity; [exact Hvalid|lia]).
  destruct (move_result turn next).
  - exact Hnext.
  - apply IH; [unfold next; rewrite move_state_history; lia|exact Hnext].
Qed.
'''
    output += position_definitions('10', WHITE10, BLACK10)
    output += f'''
Definition table10 : list cell := {rocq_list(table10)}.

Theorem safe10_leaf_checks : pairing_leafb table10 state10 = true.
Proof. vm_compute. reflexivity. Qed.

Theorem safe10_all_continuations : forall w,
  outcome (step_game 105 true state10 w (static_pairing_policy (table_mate table10))) <> WhiteWins.
Proof.
  apply (checked_pairing_leaf_policy table10 state10 105 safe10_leaf_checks state10_valid eq_refl).
Qed.

Theorem safe10_table_does_not_certify_empty_board : pairing_leafb table10 initial_state = false.
Proof. vm_compute. reflexivity. Qed.
'''
    output += position_definitions('15', WHITE_BASE[:15], BLACK_BASE[:15])
    output += f'\nDefinition replies15 : list cell := {rocq_list(replies)}.\n'
    output += '\nDefinition tables15 : list (list cell) := [\n  '
    output += ';\n  '.join(map(rocq_list, tables)) + '\n].\n'
    output += '''
Definition tree15 : DefenseCertificate :=
  DefenseNode (fun c => nth c replies15 0)
    (fun c => PairingLeaf (nth c tables15 [])).

Theorem tree15_checks_all_white_moves : certificateb tree15 state15 = true.
Proof. vm_compute. reflexivity. Qed.

Theorem state15_full_game_nonloss : solve prevents_white false 95 true state15 = true.
Proof.
  exact (checked_defense_tree_minimax tree15 state15 95
    tree15_checks_all_white_moves state15_valid eq_refl).
Qed.

Theorem state15_total_defense : exists b : BlackStrategy, forall w : WhiteStrategy,
  outcome (step_game 95 true state15 w b) <> WhiteWins.
Proof.
  exact (checked_tree_has_total_defense tree15 state15 95
    tree15_checks_all_white_moves state15_valid eq_refl).
Qed.

Theorem local_tree_does_not_certify_empty_board : certificateb tree15 initial_state = false.
Proof. vm_compute. reflexivity. Qed.

Print Assumptions safe10_all_continuations.
Print Assumptions tree15_checks_all_white_moves.
Print Assumptions state15_full_game_nonloss.
Print Assumptions state15_total_defense.
Print Assumptions local_tree_does_not_certify_empty_board.
'''
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().with_name('Witnesses.v')
    source = generate()
    if args.check:
        if target.read_text(encoding='utf-8') != source:
            raise RuntimeError('Witnesses.v differs from deterministic generator output')
        print('Witness source reproduced exactly; 95 legal White branches covered.')
    else:
        target.write_text(source, encoding='utf-8')
        print(f'Wrote {target}: safe10 leaf and a 95-branch local defense tree.')


if __name__ == '__main__':
    main()
